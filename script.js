const textNodes = new Map();
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
  acceptNode(node) {
    if (!node.nodeValue.trim() || node.parentElement?.closest('script, style')) return NodeFilter.FILTER_REJECT;
    return NodeFilter.FILTER_ACCEPT;
  }
});

while (textWalker.nextNode()) textNodes.set(textWalker.currentNode, textWalker.currentNode.nodeValue);

const translatedAttributes = [];
document.querySelectorAll('[aria-label], [placeholder], [alt], [title]').forEach((element) => {
  ['aria-label', 'placeholder', 'alt', 'title'].forEach((attribute) => {
    if (element.hasAttribute(attribute)) translatedAttributes.push([element, attribute, element.getAttribute(attribute)]);
  });
});

let currentLanguage = 'en';

function applyLanguage(language) {
  currentLanguage = language === 'ru' ? 'ru' : 'en';
  document.documentElement.lang = currentLanguage;

  textNodes.forEach((original, node) => {
    const key = original.trim();
    const translated = currentLanguage === 'en' ? (englishText[key] || key) : key;
    node.nodeValue = key ? original.replace(key, translated) : original;
  });

  translatedAttributes.forEach(([element, attribute, original]) => {
    element.setAttribute(attribute, currentLanguage === 'en' ? (englishAttributes[original] || original) : original);
  });

  document.querySelectorAll('[data-href-en][data-href-ru]').forEach((link) => {
    link.setAttribute('href', link.dataset[`href${currentLanguage === 'en' ? 'En' : 'Ru'}`]);
  });

  document.querySelectorAll('[data-language]').forEach((button) => {
    const active = button.dataset.language === currentLanguage;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });

  const languageControl = document.querySelector('.language-switch');
  if (languageControl) languageControl.setAttribute('aria-label', currentLanguage === 'en' ? 'Language' : 'Язык');

  document.title = currentLanguage === 'en' ? 'Kodvolt Digital — websites for business' : 'Kodvolt Digital — сайты для бизнеса';
  document.querySelector('meta[name="description"]')?.setAttribute('content', currentLanguage === 'en'
    ? 'Kodvolt Digital — turnkey websites and digital systems for business.'
    : 'Kodvolt Digital — разработка сайтов и цифровых систем для бизнеса под ключ.');

  try { localStorage.setItem('kodvolt-language', currentLanguage); } catch (_) { /* Storage may be disabled. */ }
}

document.querySelectorAll('[data-language]').forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.language));
});

